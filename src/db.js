'use strict';
/**
 * PostgreSQL (Supabase) data layer.
 *
 * db.query(sql, params)  → rows
 * db.one(sql, params)    → first row or undefined
 * db.tx(async (t) => …)  → runs in one transaction on one connection; t has query/one
 *
 * Stock-changing code locks the product row (SELECT … FOR UPDATE) inside db.tx so
 * concurrent requests for the same product are serialised by Postgres.
 */
const pg = require('pg');

// Return dates/timestamps as strings (as the UI displays them) and counts as numbers.
pg.types.setTypeParser(1082, (v) => v);                    // date
pg.types.setTypeParser(1114, (v) => v.slice(0, 19));       // timestamp
pg.types.setTypeParser(1184, (v) => v.slice(0, 19));       // timestamptz
pg.types.setTypeParser(20, (v) => Number(v));              // bigint (COUNT)
pg.types.setTypeParser(1700, (v) => Number(v));            // numeric (SUM)

