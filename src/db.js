const TABLES = ['settings', 'users', 'sessions', 'login_failures', 'locations', 'code_sequences', 'products', 'pieces', 'photos', 'stock_balances', 'shortlists', 'quotations',
  'reservations', 'stock_ledger', 'incoming', 'enquiries', 'videos', 'quotation_items', 'shortlist_items', 'label_templates'];

// Supabase exposes the public schema through its REST API. Enabling row level
// security with no policies blocks that API completely; this server connects
// as the database owner, which bypasses RLS.
const LOCKDOWN = TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n');

function wrap(runner) {
  return {
    query: async (sql, params = []) => (await runner.query(sql, params)).rows,
    one: async (sql, params = []) => (await runner.query(sql, params)).rows[0],
  };
}

/**
 * Connection settings from a postgres:// URL. Passwords copied from the Supabase
 * dashboard often contain characters (# % / ? …) that are not URL-encoded and make
 * standard URL parsing fail, so fall back to splitting at the last "@".
 */
function connectionConfig(connectionString) {
  const s = String(connectionString).trim();
  if (!/^postgres(ql)?:\/\//i.test(s)) throw new Error('DATABASE_URL is not a valid postgres connection string (it should start with postgresql://)');
  try {
    new URL(s);
    return { connectionString: s };
  } catch { /* fall through to manual parsing */ }
  const m = s.match(/^postgres(?:ql)?:\/\/([^:@/]+):(.*)@([^@/:?#]+)(?::(\d+))?\/([^?#]*)(?:\?(.*))?$/);
  if (!m) throw new Error('DATABASE_URL is not a valid postgres connection string');
  let password = m[2];
  try { password = decodeURIComponent(password); } catch { /* use as typed */ }
  return { user: decodeURIComponent(m[1]), password, host: m[3], port: Number(m[4] || 5432), database: decodeURIComponent(m[5] || 'postgres') };
}

function open(connectionString = process.env.DATABASE_URL, { max = Number(process.env.DB_POOL_MAX || 3), ssl } = {}) {
  if (!connectionString) throw new Error('DATABASE_URL is not set (use your Supabase connection string)');
  const conn = connectionConfig(connectionString);
  const local = conn.host ? /^(localhost|127\.0\.0\.1)$/.test(conn.host) : /@(localhost|127\.0\.0\.1)[:/]/.test(connectionString);
  const pool = new pg.Pool({
    ...conn,
    max,
    idleTimeoutMillis: 10_000,
    // Supabase requires TLS. Its certificate chain is not in Node's default store, so
    // either provide DATABASE_CA (Supabase dashboard → Database → SSL certificate) or
    // accept the encrypted connection without chain verification.
    ssl: ssl ?? (local ? false : process.env.DATABASE_CA ? { ca: process.env.DATABASE_CA } : { rejectUnauthorized: false }),
  });
  const db = wrap(pool);
  db.pool = pool;
  db.tx = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const out = await fn(wrap(client));
      await client.query('COMMIT');
      return out;
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      client.release();
    }
  };
  db.close = () => pool.end();
  return db;
}

const SCHEMA_VERSION = require('crypto').createHash('sha256').update(SCHEMA + LOCKDOWN).digest('hex').slice(0, 16);
const MIGRATE_LOCK = 4242000;

/**
 * Create/update tables. Skipped with one cheap query when the database already has
 * this schema version; otherwise serialised with an advisory lock so instances
 * starting together cannot deadlock on ALTER TABLE.
 */
async function migrate(db) {
  // usual case: one query says the schema is current
  const cur = await db.one('SELECT version FROM schema_meta WHERE id = 1').catch((e) => {
    if (e.code === '42P01') return null;   // schema_meta does not exist yet: fresh database
    throw e;
  });
  if (cur && cur.version === SCHEMA_VERSION) return;
  await db.query('CREATE TABLE IF NOT EXISTS schema_meta (id integer PRIMARY KEY, version text NOT NULL)');
  await db.tx(async (t) => {
    await t.query('SELECT pg_advisory_xact_lock($1)', [MIGRATE_LOCK]);
    const again = await t.one('SELECT version FROM schema_meta WHERE id = 1');
    if (again && again.version === SCHEMA_VERSION) return;
    await t.query(SCHEMA);
    await t.query(LOCKDOWN);
    await t.query('ALTER TABLE schema_meta ENABLE ROW LEVEL SECURITY');
    await t.query('INSERT INTO schema_meta (id, version) VALUES (1, $1) ON CONFLICT (id) DO UPDATE SET version = EXCLUDED.version', [SCHEMA_VERSION]);
  });
}

module.exports = { open, migrate, connectionConfig, TABLES };
